"use client";

import { useState } from "react";
import { PenLine, RotateCcw } from "lucide-react";
import {
  Button, Callout, Card, Checkbox, ConfirmDialog, DescriptionList, Field, RadioGroup, StateBadge, Switch, Textarea, TextInput, useToast,
} from "@/components/ds";
import { fmtDate } from "@/lib/format";
import { FlowFrame, Sample, Section, delay, now, useYou } from "../../_shared/demo";

/* Attestation of an applicability determination, mirroring AttestModal (frontend/components/AttestModal.tsx →
   POST /applicability/determinations/{lineage}/attest): decision ADOPT or REJECT with nothing preselected, a required
   authority basis, a reason required only to reject, the same acknowledgement, and the stored outcomes ATTESTED and
   DECLINED. The statement text is generated by the server and is not reproduced here. */

const DET = { id: "DET-DEMO-17", title: "Register of ICT third-party arrangements", ref: "DORA Art. 28(3)", subject: "Northwind B.V. (NL)", state: "IN_REVIEW", outcome: "APPLIES", rule: "Rule version 3.1", evaluated: "2026-10-30" };
const OBLIGATIONS = [
  { key: "DORA.28.3.REGISTER", title: "Maintain a register of all ICT third-party arrangements" },
  { key: "DORA.28.3.REPORT", title: "Report the register to the competent authority each year" },
];
const FACTS = [
  { fact: "entity.financial_entity_type", value: "Credit institution", source: "Registry filing, Mar 2026" },
  { fact: "entity.ict_third_party_count", value: "14", source: "Vendor register export, Oct 2026" },
  { fact: "entity.establishment", value: "EU (NL)", source: "Entity record" },
];
const ACK = "I have reviewed the evaluation trace, its facts and source mappings, and I make this decision personally under the authority stated.";

export function AttestationFlow() {
  return (
    <FlowFrame id="attestation" title="Attestation"
      intro="Review what the determination says and the facts behind it, state your authority, then sign ADOPT or REJECT. Adoption turns the determination into binding obligations; it is a personal act recorded with your identity."
      app={{ screen: "Applicability Review › Adoption attestation", route: "/applicability", action: "POST /applicability/determinations/{lineage}/attest", permission: "attest",
        enforced: ["Human accounts only; agents and services cannot attest", "Only PROPOSED or IN_REVIEW determinations (or ADOPTED ones flagged for review)", "UNCERTAIN outcomes cannot be adopted (409)", "A newer evaluation since you opened it is refused (409)", "A rejection needs a reason (422)"] }}
      empty={{ title: "No determinations await your attestation", description: "Determinations appear here once an evaluation proposes them." }}>
      <AttestationSteps />
    </FlowFrame>
  );
}

function AttestationSteps() {
  const toast = useToast();
  const you = useYou();
  const [decision, setDecision] = useState("");
  const [basis, setBasis] = useState("");
  const [reason, setReason] = useState("");
  const [ack, setAck] = useState(false);
  const [tried, setTried] = useState(false);
  const [confirming, setConfirming] = useState(false);
  const [stale, setStale] = useState(false);
  const [signed, setSigned] = useState<{ decision: string; basis: string; reason: string; at: string } | null>(null);
  const reasonError = tried && decision === "REJECT" && !reason.trim() ? "Enter the reason for rejecting. A rejection without a reason is refused." : undefined;
  const signLabel = decision === "ADOPT" ? "Sign adoption" : decision === "REJECT" ? "Sign rejection" : "Sign decision";
  const outcome = (d: string) => (d === "ADOPT" ? "ATTESTED" : "DECLINED");

  const sign = () => { setTried(true); if (decision === "REJECT" && !reason.trim()) return; setConfirming(true); };
  const confirm = async () => {
    await delay(900);
    if (stale) throw new Error("The server refused the signature: a newer evaluation exists for this determination (HTTP 409). Review the new evaluation before signing. (Demonstration.)");
    setSigned({ decision, basis: basis.trim(), reason: reason.trim(), at: now() });
    toast(`${outcome(decision)} (demo: nothing was recorded)`, decision === "ADOPT" ? "good" : "info");
  };

  if (signed) {
    const adopted = signed.decision === "ADOPT";
    return (
      <Card bodyClassName="p-card space-y-5">
        <div role="status" className="flex flex-wrap items-center gap-3">
          <StateBadge code={outcome(signed.decision)} status={adopted ? "verified" : "critical"} />
          <span className="type-secondary text-fg-secondary">Determination is now</span>
          <StateBadge code={adopted ? "ADOPTED" : "REJECTED"} status={adopted ? "verified" : "critical"} />
        </div>
        <DescriptionList items={[
          ["Determination", `${DET.id} · ${DET.title}`], ["Decision", <code key="d" className="type-code">{signed.decision}</code>],
          ["Signed by", `${you.name} (${you.roles})`], ["Authority basis", signed.basis],
          ["Reason", signed.reason || "None given (optional when adopting)"], ["Signed at", fmtDate(signed.at, true)],
          ...(adopted ? [["Obligations created", OBLIGATIONS.map((o) => o.key).join(", ")] as [string, string]] : []),
        ]} />
        <Callout tone="info" title="What the application would record">
          The server writes a new determination revision, generates the attestation statement and records it with your identity and authority basis.
          This demonstration recorded nothing, and this screen is not an attestation.
        </Callout>
        <Button variant="secondary" icon={RotateCcw} onClick={() => { setSigned(null); setDecision(""); setReason(""); setAck(false); setTried(false); }}>Sign again</Button>
      </Card>
    );
  }

  return (
    <div className="grid gap-stack xl:grid-cols-[minmax(0,1fr)_26rem]">
      <Card bodyClassName="p-card space-y-6">
        <Section title="Attestation summary" aside={<StateBadge code={DET.state} size="sm" />}>
          <DescriptionList items={[
            ["Determination", <span key="t">{DET.id} · {DET.title}<Sample /></span>], ["Requirement", DET.ref], ["Subject", DET.subject],
            ["Evaluation outcome", <StateBadge key="o" code={DET.outcome} size="sm" />], ["Rule", DET.rule], ["Evaluated", fmtDate(DET.evaluated)],
          ]} />
        </Section>
        <Section title="Obligations adoption would create">
          <ul className="divide-y divide-line rounded-card border border-line">
            {OBLIGATIONS.map((o) => <li key={o.key} className="px-4 py-3"><code className="type-code text-accent-fg">{o.key}</code><p className="type-secondary text-fg">{o.title}</p></li>)}
          </ul>
        </Section>
        <Section title="Supporting evidence: facts used by the evaluation">
          <ul className="divide-y divide-line rounded-card border border-line">
            {FACTS.map((f) => (
              <li key={f.fact} className="flex flex-wrap items-start justify-between gap-2 px-4 py-3">
                <span className="min-w-0"><code className="block type-code text-fg-muted">{f.fact}</code><span className="type-secondary font-medium text-fg">{f.value}</span><span className="block type-caption text-fg-muted">{f.source}</span></span>
                <StateBadge code="CURRENT" size="sm" />
              </li>
            ))}
          </ul>
        </Section>
      </Card>

      <Card title="Your decision" description="Recorded with your identity. Nothing is preselected." bodyClassName="p-card space-y-5">
        <Field label="Authority basis" required hint={you.authority ? <>Your account records: “{you.authority}”. <button type="button" className="font-medium text-accent-fg underline underline-offset-2" onClick={() => setBasis(you.authority!)}>Use it</button></> : "Name the delegation or role under which you decide."}>
          <TextInput value={basis} onChange={(e) => setBasis(e.target.value)} placeholder="Enter your applicable authority basis" />
        </Field>
        <RadioGroup legend="Decision" required name="attest-decision" value={decision} onChange={setDecision} options={[
          { value: "ADOPT", label: "ADOPT", description: "Recorded as ATTESTED; the obligations become binding" },
          { value: "REJECT", label: "REJECT", description: "Recorded as DECLINED; a reason is required" },
        ]} />
        <Field label="Reason" required={decision === "REJECT"} optional={decision === "ADOPT"} error={reasonError}>
          <Textarea rows={3} value={reason} onChange={(e) => setReason(e.target.value)} placeholder={decision === "REJECT" ? "Why does this determination not hold?" : "Optional context for the record"} />
        </Field>
        <Checkbox label={ACK} checked={ack} onChange={(e) => setAck(e.target.checked)} />
        <div className="rounded-control border border-line bg-surface-raised px-3 py-2.5 type-caption text-fg-secondary">
          <span className="font-semibold text-fg">Decision summary: </span>
          {decision ? <>{decision} → <code className="type-code">{outcome(decision)}</code>, signed by {you.name}{basis.trim() ? `, under “${basis.trim()}”` : ", authority basis still needed"}.</> : "Choose ADOPT or REJECT."}
        </div>
        <Switch label="Simulate a newer evaluation" description="The server refuses the signature (409) because the determination changed after you opened it." checked={stale} onChange={setStale} />
        <Button variant={decision === "REJECT" ? "danger" : "primary"} icon={PenLine} fullWidth disabled={!decision || !ack || !basis.trim()} onClick={sign}>{signLabel}</Button>
      </Card>

      {confirming && (
        <ConfirmDialog title={`${signLabel}?`} confirmLabel={signLabel} busyLabel="Signing…" tone={decision === "REJECT" ? "danger" : "default"} onClose={() => setConfirming(false)} onConfirm={confirm}>
          <p>You sign <code className="type-code">{decision}</code> for {DET.id}, recorded as <code className="type-code">{outcome(decision)}</code>, under “{basis.trim()}”.</p>
          <p>In the application this is a personal act recorded with your identity. This demonstration records nothing.</p>
        </ConfirmDialog>
      )}
    </div>
  );
}
