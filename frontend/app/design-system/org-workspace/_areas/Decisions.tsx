"use client";

import { useMemo, useState } from "react";
import { PenLine } from "lucide-react";
import {
  Button, Callout, Card, Checkbox, ConfirmDialog, DataTable, DescriptionList, Field, KpiCard, Modal, RadioGroup, SearchInput, StateBadge, TabPanel, Tabs, TextInput,
  Textarea, Timeline, useToast, type DataColumn, type TimelineItem,
} from "@/components/ds";
import { fmtDate } from "@/lib/format";
import { DemoFrame, Sample, Section, delay, now, useYou } from "../../_shared/demo";
import { DETERMINATIONS, EVIDENCE, OBLIGATIONS, entityName, type Determination } from "./data";
import { AreaLink, FlowLink, Proposed, SPLIT, useDetailPanel } from "./shared";

/* Decisions & attestations, mirroring Applicability Review and AttestModal (app/applicability,
   components/AttestModal.tsx → POST /applicability/determinations/{lineage}/attest). A determination records the
   applicability outcome (APPLIES, DOES_NOT_APPLY, UNCERTAIN), its state (PROPOSED, IN_REVIEW, ADOPTED, REJECTED), the
   facts it rests on and its basis. Attesting takes a decision (ADOPT or REJECT, nothing preselected), a required
   authority basis, a reason required only to reject and an acknowledgement; it is stored as ATTESTED or DECLINED.
   UNCERTAIN outcomes cannot be adopted. The statement text is generated by the server and is not reproduced here. */

const STATES = ["ALL", "PROPOSED", "IN_REVIEW", "ADOPTED", "REJECTED"];
const open = (d: Determination) => d.state === "PROPOSED" || d.state === "IN_REVIEW";
const BLANK = { decision: "", authority: "", reason: "", ack: false };

export function Decisions({ go }: { go: (id: string) => void }) {
  return (
    <DemoFrame id="ow-decisions" plane="workspace" title="Decisions & attestations"
      intro="Whether each obligation applies to an entity, the facts and rule that decided it, and the signed attestation by which someone accountable adopted or declined it."
      app={{ screen: "Applicability Review › Adoption attestation", route: "/applicability", action: "POST /applicability/determinations/{lineage}/attest", permission: "attest",
        enforced: ["Human accounts only; agents and services cannot attest", "Only PROPOSED or IN_REVIEW determinations (or ADOPTED ones flagged for review)", "UNCERTAIN outcomes cannot be adopted (409)", "A newer evaluation since you opened it is refused (409)", "A rejection needs a reason (422)"] }}
      availability={{ level: "available", note: "Determinations, their facts, challenges and attestation exist. Search and the summary figures here are presentation proposals; the dashboard reports the same counts." }}
      empty={{ title: "No determinations yet", description: "Determinations appear once an evaluation runs against an entity's facts." }}>
      <Body go={go} />
    </DemoFrame>
  );
}

function Body({ go }: { go: (id: string) => void }) {
  const toast = useToast();
  const you = useYou();
  const [dets, setDets] = useState<Determination[]>(DETERMINATIONS);
  const [q, setQ] = useState("");
  const [state, setState] = useState("ALL");
  const [selected, setSelected] = useState(DETERMINATIONS[0].lineage);
  const [attesting, setAttesting] = useState(false);
  const [confirming, setConfirming] = useState(false);
  const [form, setForm] = useState(BLANK);
  const [tried, setTried] = useState(false);
  const { ref, reveal } = useDetailPanel();

  const base = useMemo(() => dets.filter((d) => !q.trim() || `${d.title} ${d.obligation} ${entityName(d.entity)} ${d.rule}`.toLowerCase().includes(q.trim().toLowerCase())), [dets, q]);
  const shown = base.filter((d) => state === "ALL" || d.state === state);
  const current = dets.find((d) => d.lineage === selected);
  const uncertain = current?.outcome === "UNCERTAIN";

  const errors = {
    decision: !form.decision ? "Choose whether to adopt or reject." : undefined,
    authority: form.authority.trim().length < 3 ? "State the authority under which you attest (for example your role and its delegation)." : undefined,
    reason: form.decision === "REJECT" && form.reason.trim().length < 3 ? "Give the reason for rejecting; the server refuses a rejection without one (422)." : undefined,
    ack: !form.ack ? "Confirm the acknowledgement to sign." : undefined,
  };
  const show = (k: keyof typeof errors) => (tried ? errors[k] : undefined);

  const start = () => { setForm({ ...BLANK, authority: you.authority ?? "" }); setTried(false); setAttesting(true); };
  const sign = async () => {
    await delay(900);
    const adopt = form.decision === "ADOPT";
    setDets((ds) => ds.map((d) => (d.lineage === current!.lineage ? { ...d, state: adopt ? "ADOPTED" : "REJECTED",
      attestations: [...d.attestations, { at: now(), actor: `${you.name} (you)`, decision: adopt ? "ATTESTED" : "DECLINED", authority: form.authority.trim(), reason: form.reason.trim() || undefined, seq: 0 }] } : d)));
    toast(`${current!.obligation}: ${adopt ? "ATTESTED, determination ADOPTED" : "DECLINED, determination REJECTED"} (simulated: nothing was signed)`, adopt ? "good" : "warn");
  };

  const columns: DataColumn<Determination>[] = [
    { key: "title", header: "Determination", sortValue: (d) => d.title, render: (d) => <><span className="block font-medium text-fg">{d.title}</span><code className="type-code text-fg-muted">{d.lineage} · {d.obligation}</code></> },
    { key: "entity", header: "Entity", sortValue: (d) => entityName(d.entity), render: (d) => entityName(d.entity) },
    { key: "outcome", header: "Outcome", sortValue: (d) => d.outcome, render: (d) => <StateBadge code={d.outcome} size="sm" /> },
    { key: "state", header: "State", sortValue: (d) => d.state, render: (d) => <StateBadge code={d.state} size="sm" /> },
    { key: "evaluated", header: "Evaluated", sortValue: (d) => d.evaluated, render: (d) => <span className="whitespace-nowrap tabular-nums">{fmtDate(d.evaluated)}</span> },
    { key: "open", header: <span className="sr-only">Details</span>, align: "right", render: (d) => (
      <Button size="sm" variant={d.lineage === selected ? "secondary" : "ghost"} aria-pressed={d.lineage === selected} onClick={() => { setSelected(d.lineage); reveal(); }}>
        {d.lineage === selected ? "Viewing" : "View"}<span className="sr-only"> {d.title}</span>
      </Button>
    ) },
  ];

  const history: TimelineItem[] = current ? [
    { id: "eval", title: "Evaluated", meta: `${current.rule} · ${fmtDate(current.evaluated, true)}`, description: <>Outcome <code className="type-code">{current.outcome}</code>{current.reasons.length ? <> · {current.reasons.join(", ")}</> : null}</>, status: "info" },
    ...(current.lineage === "det-22" ? [{ id: "chal", title: "Challenged", meta: "Legal Reviewer · 26 Oct 2026", description: "Moved to IN_REVIEW while the employee count is confirmed.", status: "warning" as const }] : []),
    ...current.attestations.map((a, i) => ({ id: `att-${i}`, title: a.decision, meta: `${a.actor} · ${fmtDate(a.at, true)}`, status: a.decision === "ATTESTED" ? "verified" as const : "critical" as const,
      description: <>Authority basis: {a.authority}{a.reason ? <><br />Reason: {a.reason}</> : null}</> })),
  ] : [];

  return (
    <div className="space-y-stack">
      <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-5">
        {(["PROPOSED", "IN_REVIEW", "ADOPTED", "REJECTED"] as const).map((s) => (
          <KpiCard key={s} label={s === "IN_REVIEW" ? "In review" : s[0] + s.slice(1).toLowerCase()} value={dets.filter((d) => d.state === s).length} hint={<code className="type-code">{s}</code>}
            tone={s === "ADOPTED" ? "verified" : s === "REJECTED" ? "neutral" : "warning"} />
        ))}
        <KpiCard label="Uncertain outcomes" tone="warning" value={dets.filter((d) => d.outcome === "UNCERTAIN").length} hint="cannot be adopted" />
      </div>

      <div className={SPLIT}>
        <div className="min-w-0 space-y-3">
          <div className="flex flex-wrap items-end justify-between gap-3">
            <div className="min-w-0 flex-1 sm:max-w-sm"><Field label={<>Search determinations<Proposed /></>}><SearchInput value={q} onChange={(e) => setQ(e.target.value)} onClear={() => setQ("")} placeholder="Obligation, entity or rule" /></Field></div>
            <FlowLink flow="attestation">Full Attestation flow</FlowLink>
          </div>
          <Tabs id="ow-dec-state" label="Filter by determination state" variant="pills" value={state} onChange={setState}
            items={STATES.map((s) => ({ value: s, label: s === "ALL" ? "All" : s, count: base.filter((d) => s === "ALL" || d.state === s).length }))} />
          <TabPanel id="ow-dec-state" value={state} className="">
            <DataTable caption={`Applicability determinations (sample): ${shown.length} shown`} columns={columns} rows={shown} rowKey={(d) => d.lineage} defaultSort={{ key: "evaluated", dir: "desc" }} minWidth="44rem"
              empty={{ title: "No determinations match", description: "Change the search or the state filter.", action: <Button size="sm" onClick={() => { setQ(""); setState("ALL"); }}>Clear filters</Button> }} />
          </TabPanel>
          <p className="type-caption text-fg-muted">The outcome says whether the rule applies; the determination state says whether the organization has adopted that answer.</p>
        </div>

        <div ref={ref} className="scroll-mt-6">
          {current ? (
            <Card title={current.title} description={<code className="type-code">{current.lineage} · {current.obligation}</code>} actions={<StateBadge code={current.state} size="sm" />} bodyClassName="p-card space-y-5">
              <DescriptionList columns={1} items={[
                ["Applicable obligation", OBLIGATIONS.some((o) => o.key === current.obligation) ? <AreaLink key="o" id={current.obligation} area="obligations" go={go} /> : <code key="o" className="type-code">{current.obligation}</code>],
                ["Entity", entityName(current.entity)], ["Outcome", <StateBadge key="u" code={current.outcome} size="sm" />],
                ["Basis", current.basis], ["Rule", <code key="r" className="type-code">{current.rule}</code>], ["Applies from", fmtDate(current.validFrom)],
              ]} />
              <Section title="Facts relied on">
                <ul className="divide-y divide-line rounded-card border border-line">{current.facts.map(([k, v]) => (
                  <li key={k} className="flex flex-wrap items-center justify-between gap-2 px-3 py-2"><code className="type-code text-fg-secondary">{k}</code>
                    {v === "missing" ? <StateBadge code="MISSING" size="sm" /> : <span className="type-secondary text-fg">{v}</span>}</li>
                ))}</ul>
              </Section>
              <Section title="Supporting evidence">
                {current.evidence.length ? <ul className="flex flex-wrap gap-2">{current.evidence.map((e) => <li key={e}>{EVIDENCE.some((x) => x.id === e)
                  ? <AreaLink id={e} area="evidence" go={go} label={`Open evidence ${e}`} /> : <code className="type-code text-fg-muted" title="Not among the sample evidence records">{e}</code>}</li>)}</ul>
                  : <p className="type-secondary text-fg-muted">None cited.</p>}
              </Section>
              <Section title="Decision history"><Timeline label={`History of ${current.lineage}`} items={history} /></Section>
              {uncertain && open(current) && <Callout tone="warning" title="UNCERTAIN: it cannot be adopted">Resolve the missing or conflicting facts and re-evaluate. You can still reject it with a reason.</Callout>}
              {open(current) ? <Button fullWidth variant="primary" icon={PenLine} onClick={start}>Attest this determination</Button>
                : <p className="type-secondary text-fg-muted">{current.state === "ADOPTED" ? "Adopted. It can be attested again only if flagged for review." : "Rejected. A new evaluation would propose it again."}</p>}
              <p className="type-caption text-fg-muted">Sample determination<Sample />. Attesting here signs nothing.</p>
            </Card>
          ) : <Card><p className="type-secondary text-fg-muted">Choose a determination to see its facts and history.</p></Card>}
        </div>
      </div>

      <Modal open={attesting} onClose={() => setAttesting(false)} title="Adoption attestation" description={current ? `${current.title} · ${entityName(current.entity)}` : undefined}
        footer={<>
          <Button variant="secondary" onClick={() => setAttesting(false)}>Cancel</Button>
          <Button variant="primary" icon={PenLine} onClick={() => { setTried(true); if (!Object.values(errors).some(Boolean)) { setAttesting(false); setConfirming(true); } }}>Review attestation</Button>
        </>}>
        <div className="space-y-form">
          <RadioGroup legend="Decision" name="ow-attest-decision" required value={form.decision} onChange={(v) => setForm((f) => ({ ...f, decision: v }))} error={show("decision")}
            options={[
              { value: "ADOPT", label: "Adopt", description: uncertain ? "Not available: UNCERTAIN outcomes cannot be adopted (409)." : "The organization accepts this determination; the obligation is adopted.", disabled: uncertain },
              { value: "REJECT", label: "Reject", description: "The organization does not adopt it. A reason is required." },
            ]} />
          <Field label="Authority basis" required error={show("authority")} hint="Your role and the delegation under which you sign."><TextInput value={form.authority} onChange={(e) => setForm((f) => ({ ...f, authority: e.target.value }))} /></Field>
          <Field label="Reason" required={form.decision === "REJECT"} optional={form.decision !== "REJECT"} error={show("reason")}>
            <Textarea rows={3} value={form.reason} onChange={(e) => setForm((f) => ({ ...f, reason: e.target.value }))} />
          </Field>
          <div className="space-y-1">
            <Checkbox label="I am accountable for this decision and have reviewed the facts and rule it rests on." checked={form.ack} onChange={(e) => setForm((f) => ({ ...f, ack: e.target.checked }))} />
            {show("ack") && <p className="type-caption text-status-critical">{show("ack")}</p>}
          </div>
          <p className="type-caption text-fg-muted">The server generates the attestation statement and records it with your decision; its text is not reproduced here.</p>
        </div>
      </Modal>
      {confirming && current && (
        <ConfirmDialog title={form.decision === "ADOPT" ? "Sign and adopt?" : "Sign and reject?"} confirmLabel={form.decision === "ADOPT" ? "Sign: adopt" : "Sign: reject"} busyLabel="Signing…"
          tone={form.decision === "ADOPT" ? "default" : "danger"} onClose={() => setConfirming(false)} onConfirm={sign}>
          <DescriptionList columns={1} items={[["Determination", `${current.lineage} · ${current.obligation}`], ["Stored as", form.decision === "ADOPT" ? "ATTESTED → ADOPTED" : "DECLINED → REJECTED"],
            ["Authority basis", form.authority.trim()], ...(form.reason.trim() ? [["Reason", form.reason.trim()] as [string, string]] : [])]} />
          <p>Simulated: nothing is signed or recorded, and the server is not called.</p>
        </ConfirmDialog>
      )}
    </div>
  );
}
